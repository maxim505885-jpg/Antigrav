    """Intelligent industrial structural engineer agent advising on shop drafting and norms."""
    q = req.query.lower().strip()
    
    # 1. Поиск темы запроса
    matched_topic = "general"
    if any(w in q for w in ["колонн", "колонна", "к-1", "к-2", "привязк"]):
        matched_topic = "columns"
    elif any(w in q for w in ["рельс", "подкранов", "балк", "кран", "у.г.р", "кр-70", "пути", "коле"]):
        matched_topic = "crane_girders"
    elif any(w in q for w in ["ферм", "кровл", "покрыти", "прогон", "уклон", "стропил"]):
        matched_topic = "roof_trusses"
    elif any(w in q for w in ["связ", "жесткост", "крестов", "ветров"]):
        matched_topic = "bracing_system"
    elif any(w in q for w in ["фундамент", "анкер", "баз", "подколонник"]):
        matched_topic = "foundations"
    elif any(w in q for w in ["габарит", "зазор", "шум", "очистк", "безопасн"]):
        matched_topic = "clearance_rules"
    elif any(w in q for w in ["допуск", "сп 70", "отклонен", "таблиц"]):
        matched_topic = "tolerances_sp70"
    elif any(w in q for w in ["анатом", "цех", "размер", "пролет", "длин", "ширин", "отметк"]):
        matched_topic = "workshop_anatomy"

