class AgentQueryRequest(BaseModel):
    query: str = Field(..., description="Вопрос пользователя инженеру-конструктору цехов")
    cloud_context: dict[str, Any] | None = Field(default=None, description="Текущие параметры распознанного каркаса")


class AgentAnswerResponse(BaseModel):
    topic: str
    answer: str
    recommendations: list[str]
    referenced_norms: list[str]
    cad_shortcut_tips: list[str]


